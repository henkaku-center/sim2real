def write(design: str) -> Twin:
    twin = build(design)
    model_path(design).write_text(twin.xml)
    record_path(design).write_text(twin.record_text)
    return twin


def check(design: str) -> list[str]:
    """Problems with the committed model/record of one design; empty when current."""
    try:
        twin = build(design)
    except (OSError, ValueError, KeyError) as error:
        return [f"{design}: cannot regenerate: {error}"]
    problems = []
    for path, text in ((model_path(design), twin.xml), (record_path(design), twin.record_text)):
        name = path.relative_to(REPO_ROOT).as_posix()
        if not path.exists():
            problems.append(f"{name} is missing; run `uv run python -m sim.twin`")
        elif path.read_text() != text:
            problems.append(f"{name} is stale relative to its inputs; run `uv run python -m sim.twin`")
    return problems


def check_all() -> list[str]:
    return [problem for design in generated_designs() for problem in check(design)]


def summary(record: dict) -> str:
    totals = record["totals"]
    com = [v * 1000 for v in totals["com_torso_m"]]
    by = totals["mass_by_status_kg"]
    return (f"{record['design']}: {totals['mass_kg'] * 1000:.1f} g "
            f"(estimated {by['estimated'] * 1000:.1f}, unmeasured-nominal "
            f"{by['unmeasured-nominal'] * 1000:.1f}, measured {by['measured'] * 1000:.1f}); "
            f"rest CoM ({com[0]:+.2f}, {com[1]:+.2f}, {com[2]:+.2f}) mm in the CAD frame")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--design", help="one printing design (default: every design in manifest/twin.yaml)")
    parser.add_argument("--check", action="store_true", help="fail when a committed model or record is stale")
    parser.add_argument("--summary", action="store_true", help="print masses and centre of mass only")
    args = parser.parse_args()
    designs = [args.design] if args.design else generated_designs()
    if args.check:
        problems = [problem for design in designs for problem in check(design)]
        for problem in problems:
            print(problem, file=sys.stderr)
        if not problems:
            print(f"current: {', '.join(designs)}")
        return 1 if problems else 0
    for design in designs:
        twin = build(design) if args.summary else write(design)
        if not args.summary:
            print(f"wrote {model_path(design).relative_to(REPO_ROOT)} and "
                  f"{record_path(design).relative_to(REPO_ROOT)}")
        print(summary(twin.record))
    return 0


if __name__ == "__main__":
    sys.exit(main())
