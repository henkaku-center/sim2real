"""One digital twin per printing design, generated from the design record.

Inputs (never hand-copied into the outputs):
- manifest/robot.yaml          joints, signs, limits, poses, servo nominal values
- manifest/twin.yaml           hardware default, mass table, material/fill
                               assumptions, actuator and contact parameters
- assets/printing/<design>/assembly.json   hip shafts, servo bays, PCB, battery,
                               display and switch datums (CAD frame, mm)
- the design's printable STLs and the unchanged upstream leg STLs
- sim/prepare_assets.py        hip/foot axes in the leg drawing frame

Outputs:
- models/<design>.xml                      MuJoCo model (reference engine)
- assets/printing/<design>/dynamics.json   bodies, parents, joint origins and
  axes, masses, inertias, centre of mass, joint limits, actuator and contact
  parameters, and source hashes, for consumers that do not run MuJoCo

Both come from the same in-memory build, so they cannot disagree. `--check`
regenerates them and fails on any difference from the committed files.

The upstream narrow-body baseline stays reproducible under the explicit name
`upstream-v117`: sim/build_mjcf.py writes models/sesame.xml. That generator is
a pinned input of the held body-v1 report, so it is left byte-identical.

Every mass here is an estimate or a nominal value; nothing was weighed. This
is a simulation model, not a measured description of a built robot.

Usage:
  uv run python -m sim.twin                  regenerate every listed design
  uv run python -m sim.twin --design NAME    regenerate one design
  uv run python -m sim.twin --check          exit 1 when a committed file is stale
  uv run python -m sim.twin --summary        print masses and centre of mass
"""

