def _record(design, spec, m, legs, bodies, spawn_z, timestep, actuator, force, friction, base_box,
            head_box, sources, xml) -> dict:
    origin = {"torso": np.zeros(3)}
    for body in bodies[1:]:
        origin[body.name] = origin[body.parent] + body.pos
    total = math.fsum(b.mass for b in bodies)
    com = _fsum3([np.array([b.mass * (origin[b.name] + b.com)[i] for b in bodies]) for i in range(3)]) / total
    by_status = {s: math.fsum(p.mass for b in bodies for p in b.parts if p.status == s) for s in STATUSES}
    joints = []
    for leg in legs:
        for name, body, axis in ((leg.hip, f"{leg.name}_upper", leg.hip_axis),
                                 (leg.foot, f"{leg.name}_lower", leg.foot_axis)):
            j = m.joint(name)
            joints.append({
                "name": name, "channel": j.channel, "leg": j.leg, "role": j.role, "body": body,
                "parent": next(b.parent for b in bodies if b.name == body),
                "origin_m": _nums(origin[body]), "axis": list(axis), "sign": j.sign,
                "limits_firmware_deg": list(j.limits_deg),
                "range_rad": [float(f"{v:.6f}") for v in m.internal_range(j)],
            })
    joints.sort(key=lambda item: item["channel"])
    profile = hardware_profile(spec, m)
    material = {k: {kk: v[kk] for kk in ("density_kg_m3", "status")} for k, v in spec["materials"].items()}
    profiles = {k: {kk: v[kk] for kk in ("material", "fill_fraction", "status")}
                for k, v in spec["print_profiles"].items()}
    return {
        "schema": RECORD_SCHEMA,
        "design": design,
        "status": RECORD_STATUS,
        "scope": ("Generated simulation model. Printed masses are estimated from mesh volume, "
                  "purchased parts and actuator/contact parameters are nominal. Nothing was "
                  "weighed or measured on a built robot."),
        "generated_by": "sim/twin.py",
        "engine": "MuJoCo (reference)",
        "mjcf": {"path": model_path(design).relative_to(REPO_ROOT).as_posix(),
                 "sha256": hashlib.sha256(xml.encode()).hexdigest()},
        "frame": {
            "torso": "design CAD frame: X front, Y left, Z up, origin at the CAD origin",
            "units": "SI: metres, kilograms, radians; inertia in kg m2 about each centre of mass",
            "pose": "joint origins, axes and the centre of mass are at rest (every internal angle 0)",
        },
        "hardware_profile": {
            "name": profile["name"], "status": profile["status"], "mcu_board": profile["mcu_board"],
            "servo_driver": profile["servo_driver"], "robot_yaml": profile["robot_yaml"],
        },
        "bodies": [{
            "name": b.name, "parent": b.parent, "origin_in_parent_m": _nums(b.pos),
            "mass_kg": _num(b.mass), "com_m": _nums(b.com),
            "inertia_kg_m2": {key: _num(b.inertia[i, j]) for key, (i, j) in
                              {"xx": (0, 0), "yy": (1, 1), "zz": (2, 2), "xy": (0, 1), "xz": (0, 2),
                               "yz": (1, 2)}.items()},
            "parts": [p.id for p in b.parts],
        } for b in bodies],
        "joints": joints,
        "mass_table": [{
            "id": p.id, "row": p.row, "body": b.name, "kind": p.kind, "status": p.status,
            "mass_kg": _num(p.mass), "com_torso_m": _nums(origin[b.name] + p.com), "basis": p.basis,
        } for b in bodies for p in b.parts],
        "assumptions": {
            "materials": material, "print_profiles": profiles,
            "servo_envelope": {k: v for k, v in spec["servo_envelope"].items() if k != "source"},
            "electronics_stack": {k: v for k, v in spec["electronics_stack"].items() if k != "source"},
            "leg_mount": {k: v for k, v in spec["leg_mount"].items() if k != "source"},
        },
        "totals": {
            "mass_kg": _num(total), "com_torso_m": _nums(com),
            "mass_by_status_kg": {k: _num(v) for k, v in by_status.items()},
        },
        "actuators": {
            "type": "position servo", "status": actuator["status"], "kp_Nm_per_rad": actuator["kp_Nm_per_rad"],
            "force_limit_Nm": force, "no_load_speed_rad_s": _num(actuator["no_load_speed_rad_s"]),
            "joint_damping_Nm_s_per_rad": _num(actuator["joint_damping_Nm_s_per_rad"]),
            "joint_damping_rule": "force_limit_Nm / no_load_speed_rad_s (linear torque-speed line)",
            "order": [j.name for j in m.joints],
        },
        "contact": {
            "status": spec["contact"]["status"], "floor_friction": friction,
            "collision_boxes_m": {
                "torso_geom": {"centre": _nums(base_box[0]), "half_size": _nums(base_box[1])},
                "torso_head_geom": {"centre": _nums(head_box[0]), "half_size": _nums(head_box[1])},
                **{f"{leg.name}_{role}_geom": {"centre": _nums(box[0]), "half_size": _nums(box[1])}
                   for leg in legs for role, box in (("upper", leg.upper_box), ("lower", leg.lower_box))},
            },
        },
        "simulation": {"timestep_s": timestep, "spawn_height_m": _num(spawn_z)},
        "source_hashes": {p.relative_to(REPO_ROOT).as_posix(): _sha(p) for p in sources},
    }


