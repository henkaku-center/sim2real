"""Synthetic "real" runs: the current model with hidden parameter changes.

Used to prove the record -> track -> fit -> report pipeline end to end without
hardware. The commands come from the real recorder driving the simulated
firmware; the torso track comes from a MuJoCo rollout with hidden parameter
values, seen through an arbitrary camera frame, with sensor noise and an
unknown video-to-host time offset. Logs are labelled ``synthetic`` and carry
the hidden truth in the header (the fit never reads it). This validates the
pipeline only: no robot was measured.
"""

from __future__ import annotations

import math

from pathlib import Path

import mujoco
import numpy as np

from sim.manifest import Manifest
from sim.real2sim import fit as fitting
from sim.real2sim import geometry as g
from sim.real2sim import recorder, runlog

MARKER_ORIGIN_IN_TORSO_M = (0.0, 0.0, 0.019)  # lid top above the torso centre (model value, unmeasured)


def torso_track(model: mujoco.MjModel, log: runlog.RunLog, values: dict[str, float],
                manifest: Manifest | None = None):
    """Simulated torso track (times, positions, quaternions) for a command log."""
    view = fitting.ModelView(model, manifest)
    dt = float(model.opt.timestep)
    t_end = next(c["t"] for c in reversed(log.commands) if c["text"] == "off")
    nstep = int(math.ceil(t_end / dt))
    run = fitting.Run(name="synthetic", log=log, nstep=nstep,
                      ctrl=fitting.command_reference(log, view, dt, nstep),
                      rest=(0.0, 0.0), t_end=t_end, marker_origin=np.zeros(3))
    simulator = fitting.Simulator(view, threads=1)
    try:
        track_p, track_q = simulator.tracks(run, [values])
    finally:
        simulator.close()
    return np.arange(nstep + 1) * dt, track_p[0], track_q[0]


def _commands_and_track(model, sequence, hidden, time_offset_s, fps, slew_rate_deg_s, manifest):
    """Dry-run the recorder, simulate the hidden robot, sample it at video frame times."""
    header, records = recorder.dry_run(sequence, slew_rate_deg_s=slew_rate_deg_s, manifest=manifest)
    commands = runlog.from_records(header, records)
    times, track_p, track_q = torso_track(model, commands, hidden, manifest)
    # Video frames cover the whole run; frames before the log starts see the resting robot.
    frames = np.arange(0.0, times[-1] - time_offset_s, 1.0 / fps)
    torso_p, torso_q = fitting._sample(track_p, track_q, times[1] - times[0], frames + time_offset_s)
    header = dict(header)
    header["evidence"] = "synthetic"
    header["clocks"] = {**header["clocks"], "video": "seconds since the first synthetic video frame"}
    header["synthetic"] = {
        "statement": "Generated by simulation. Validates the pipeline only; no robot was measured.",
        "hidden_parameters": dict(hidden), "hidden_time_offset_s": time_offset_s, "fps": fps}
    return header, records, frames, torso_p, torso_q


def synthesize(model: mujoco.MjModel, sequence: str, hidden: dict[str, float], *, seed: int,
               time_offset_s: float = 0.137, fps: float = 60.0, noise_position_m: float = 0.001,
               noise_attitude_deg: float = 0.5, slew_rate_deg_s: float | None | str = "manifest",
               manifest: Manifest | None = None,
               marker_origin_in_torso_m=MARKER_ORIGIN_IN_TORSO_M) -> tuple[dict, list[dict]]:
    """Return (header, records) of a synthetic run log with noisy torso poses.

    ``hidden`` are parameter values (names from fit.PARAMS) the "real" robot
    has; ``time_offset_s`` is the hidden host = video + offset.
    """
    rng = np.random.default_rng(seed)
    header, records, frames, torso_p, torso_q = _commands_and_track(
        model, sequence, hidden, time_offset_s, fps, slew_rate_deg_s, manifest)

    # Marker on the lid, seen in an arbitrary fixed camera frame.
    origin = np.asarray(marker_origin_in_torso_m, dtype=float)
    marker_p = torso_p + g.rotate(torso_q, origin)
    camera_q = g.from_rotvec(rng.normal(size=3) * 1.2)
    camera_p = np.array([0.05, -0.02, 0.45]) + rng.normal(size=3) * 0.05
    marker_p, marker_q = g.compose(camera_p, camera_q, marker_p, torso_q)
    marker_p = marker_p + rng.normal(size=marker_p.shape) * noise_position_m
    jitter = g.from_rotvec(rng.normal(size=marker_p.shape) * math.radians(noise_attitude_deg))
    marker_q = g.mul(marker_q, jitter)

    header["channels"] = {"torso_pose": runlog.torso_pose_channel(
        frame="camera",
        frame_definition="arbitrary fixed synthetic camera frame (seeded); the fit only uses motion relative to rest",
        marker_origin_in_torso_m=list(origin),
        source="synthetic: simulated torso track plus Gaussian noise, no camera involved")}
    header["synthetic"].update(seed=seed, noise_position_m=noise_position_m, noise_attitude_deg=noise_attitude_deg)
    poses = runlog.pose_records(frames, marker_p, marker_q, clock="video")
    return header, records + poses


def synthesize_video(model: mujoco.MjModel, sequence: str, hidden: dict[str, float], video_path: Path | str, *,
                     seed: int, time_offset_s: float = 0.137, fps: float = 30.0,
                     slew_rate_deg_s: float | None | str = "manifest", manifest: Manifest | None = None,
                     marker_origin_in_torso_m=MARKER_ORIGIN_IN_TORSO_M, size=(1280, 720)):
    """Write a synthetic fixed-camera video of the marker and return (header, records, camera).

    The log has commands only; the marker tracker must add the torso poses,
    exactly as it would for a real video. The camera is an ideal pinhole.
    """
    import cv2

    from sim.real2sim import marker

    header, records, frames, torso_p, torso_q = _commands_and_track(
        model, sequence, hidden, time_offset_s, fps, slew_rate_deg_s, manifest)
    camera = marker.guessed_camera(size)
    camera.calibrated, camera.source = True, "synthetic ideal pinhole (known exactly)"
    world_p, world_q = marker.look_at([0.06, -0.42, 0.34], [0.06, 0.0, 0.03])
    head_texture, head_w = marker.marker_texture(marker.HEAD_ID, marker.HEAD_SIZE_MM)
    floor_texture, floor_w = marker.marker_texture(marker.FLOOR_ID, marker.FLOOR_SIZE_MM)
    floor_pose = g.compose(world_p, world_q, np.array([0.19, 0.0, 0.0]), np.array([1.0, 0.0, 0.0, 0.0]))
    origin = np.asarray(marker_origin_in_torso_m, dtype=float)
    marker_p = torso_p + g.rotate(torso_q, origin)
    marker_q = g.mul(torso_q, g.conj(marker.BODY_FROM_MARKER))
    writer = cv2.VideoWriter(str(video_path), cv2.CAP_OPENCV_MJPEG, cv2.VideoWriter_fourcc(*"MJPG"), fps, size)
    if not writer.isOpened():
        raise RuntimeError(f"cannot write video {video_path}")
    try:
        for k in range(len(frames)):
            head_pose = g.compose(world_p, world_q, marker_p[k], marker_q[k])
            image = marker.render(camera, [(floor_texture, floor_w, floor_w, *floor_pose),
                                           (head_texture, head_w, head_w, *head_pose)], seed=seed * 100003 + k)
            writer.write(cv2.cvtColor(image, cv2.COLOR_GRAY2BGR))
    finally:
        writer.release()
    header["synthetic"].update(seed=seed, video="rendered marker video, ideal pinhole camera, pixel noise")
    return header, records, camera
