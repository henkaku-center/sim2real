"""Manifest-derived vocabulary, JSON Schema and semantic validation."""
import hashlib
import json
import math
import re

import yaml

from . import ROOT
import joints
import generate_s3_firmware

MAX_STEPS = 32
MAX_DURATION_MS = 120_000


class InvalidPlan(ValueError):
    pass


def require(ok, reason):
    if not ok:
        raise InvalidPlan(reason)


def object_schema(properties):
    return {"type": "object", "properties": properties, "required": list(properties),
            "additionalProperties": False}


class Catalog:
    def __init__(self):
        self.interface, evidence = joints.load()
        # The PTY uses the generated C++ sequences; refuse stale generated bytes.
        require(generate_s3_firmware.OUT.read_text() == generate_s3_firmware.render(),
                "Stale generated firmware; run tools/generate_s3_firmware.py")
        self.robot = yaml.safe_load((ROOT / "manifest/robot.yaml").read_text())
        self.motions = yaml.safe_load((ROOT / "manifest/motions.yaml").read_text())["motions"]
        self.order = [j["name"] for j in self.interface["joint_map"]]
        self.entries = {n: joints.describe(n, self.interface, evidence) for n in self.order}
        self.rate = self.interface["safeaction"]["controller_rate_deg_s"]
        self.rest = [self.robot["poses"]["rest"][n] for n in self.order]
        source = (ROOT / "firmware/sesame-s3/vendor/face-bitmaps.h").read_text()
        face_list = source.split("#define FACE_LIST", 1)[1].split("#define X", 1)[0]
        # setFace requires a non-null first frame, not just a weak declaration.
        self.faces = [n for n in re.findall(r"X\((\w+)\)", face_list)
                      if re.search(r"epd_bitmap_" + n + r"\s*\[\s*\]\s*PROGMEM\s*=", source)]
        sources = ["manifest/robot.yaml", "manifest/motions.yaml", "manifest/safeaction.yaml",
                   "firmware/sesame-s3/controller.cpp", "firmware/sesame-s3/safe_action.h",
                   "firmware/sesame-s3/command_line.h", "firmware/sesame-s3/vendor/face-bitmaps.h"]
        self.contract = hashlib.sha256(b"".join((ROOT / p).read_bytes() for p in sources)).hexdigest()
        self.unavailable = {}
        for name in self.motions:
            try:
                for targets, _ in self.expand(name):
                    for joint, angle in targets.items():
                        self.check_angle(joint, angle)
            except InvalidPlan as exc:
                self.unavailable[name] = str(exc)
        self.available = [n for n in self.motions if n not in self.unavailable]

    def expand(self, name):
        def walk(steps):
            for step in steps:
                if "repeat" in step:
                    for _ in range(step["repeat"]["count"]):
                        yield from walk(step["repeat"]["steps"])
                else:
                    yield (self.robot["poses"][step["pose"]] if "pose" in step
                           else step.get("set", {})), step.get("wait", 0)
        return walk(self.motions[name])

    def check_angle(self, name, value):
        try:
            finite = type(value) in (int, float) and math.isfinite(value)
        except OverflowError:
            finite = False
        require(finite, f"{name}: angle must be finite")
        entry = self.entries[name]
        problem = joints.assess(name, value, entry, False)
        require(problem is None, problem)
        lo, hi = entry["soft_limits_deg"]
        require(lo <= value <= hi, f"{name}: {value} outside soft limits {lo}..{hi}")

    def check_pose(self, angles):
        require(isinstance(angles, list) and len(angles) == 8, "pose needs eight angles in " + " ".join(self.order))
        for n, v in zip(self.order, angles):
            self.check_angle(n, v)

    def motion_timing(self, name, previous):
        # Same expanded sequence as generate_s3_firmware. Wait-only rows run
        # after the preceding target settles; include scheduler slack per row.
        duration = 0
        current = list(previous)
        for targets, wait in self.expand(name):
            target = [targets.get(n, v) for n, v in zip(self.order, current)]
            duration += math.ceil(max(abs(a-b) for a, b in zip(current, target)) / self.rate * 1000) + wait + 25
            current = target
        return duration + 500, current

    def plan(self, steps):
        return {"version": 1, "contract": self.contract, "steps": steps}

    def schema(self):
        hold = {"type": "integer", "minimum": 0, "maximum": 10000}
        def step(kind, **props):
            return object_schema({"type": {"type": "string", "enum": [kind]}, **props})
        return object_schema({
            "version": {"type": "integer", "enum": [1]},
            "contract": {"type": "string", "enum": [self.contract]},
            "steps": {"type": "array", "minItems": 1, "maxItems": MAX_STEPS, "items": {"anyOf": [
                step("motion", name={"type": "string", "enum": self.available}),
                step("face", name={"type": "string", "enum": self.faces}, hold_ms=hold),
                step("pose", angles={"type": "array", "items": {"type": "number", "minimum": 0, "maximum": 180},
                                     "minItems": 8, "maxItems": 8},
                     duration_ms={"type": "integer", "minimum": 100, "maximum": 10000}, hold_ms=hold),
                step("rest"),
            ]}},
        })

    def validate(self, plan):
        require(isinstance(plan, dict) and set(plan) == {"version", "contract", "steps"}, "plan fields: version, contract, steps only")
        require(type(plan["version"]) is int and plan["version"] == 1, "unsupported plan version")
        require(plan["contract"] == self.contract, "server/Pi firmware contract mismatch")
        steps = plan["steps"]
        require(isinstance(steps, list) and 1 <= len(steps) <= MAX_STEPS, f"plan needs 1..{MAX_STEPS} steps")
        previous, total = list(self.rest), 0
        budgets = []
        for i, step in enumerate(steps):
            require(isinstance(step, dict), f"step {i}: expected object")
            kind = step.get("type")
            require(kind != "face_bitmap", "face_bitmap is reserved: this firmware accepts named faces only; custom OLED images are not supported")
            fields = {"motion": {"type", "name"}, "face": {"type", "name", "hold_ms"},
                      "pose": {"type", "angles", "duration_ms", "hold_ms"}, "rest": {"type"}}
            require(isinstance(kind, str) and kind in fields, f"step {i}: unknown step type")
            require(set(step) == fields[kind], f"step {i}: expected fields {sorted(fields[kind])}")
            for key in ("duration_ms", "hold_ms"):
                if key in step:
                    require(type(step[key]) is int and (100 if key == "duration_ms" else 0) <= step[key] <= 10000,
                            f"step {i}: invalid {key}")
            if kind in ("motion", "rest"):
                name = "rest" if kind == "rest" else step["name"]
                require(isinstance(name, str) and name in self.motions, f"step {i}: unknown motion")
                require(name not in self.unavailable, f"motion {name} outside fitted travel: {self.unavailable.get(name)}")
                budget, previous = self.motion_timing(name, previous)
            elif kind == "face":
                require(step["name"] in self.faces, f"step {i}: unknown face")
                budget = step["hold_ms"] + 500
            else:
                self.check_pose(step["angles"])
                minimum = math.ceil(max(abs(a-b) for a, b in zip(previous, step["angles"])) / self.rate * 1000)
                require(step["duration_ms"] >= minimum, f"step {i}: duration_ms needs at least {minimum} at firmware rate {self.rate} deg/s")
                previous = list(step["angles"])
                budget = step["duration_ms"] + step["hold_ms"] + 1000
            total += budget
            budgets.append(budget)
        require(total <= MAX_DURATION_MS, f"plan duration bound {total} ms exceeds {MAX_DURATION_MS} ms")
        return budgets


if __name__ == "__main__":
    print(json.dumps(Catalog().schema(), indent=2))
